function updatePackageSpec(spec, latest) {
  const prefix = spec.startsWith("^") ? "^" : spec.startsWith("~") ? "~" : "";
  return `${prefix}${latest}`;
}
function safeDependencyUpdate() {
  info("Checking for outdated packages...");
  const result = run(NPM, ["outdated", "--json"], { capture: true, allowed: [0, 1] });
  let outdated = {};
  try { outdated = JSON.parse(result.stdout || "{}"); } catch { outdated = {}; }
  const pkgPath = join(ROOT, "package.json");
  const pkg = JSON.parse(readFileSync(pkgPath, "utf8"));
  const changed = [];
  const held = [];
  for (const section of ["dependencies", "devDependencies"]) {
    for (const [name, spec] of Object.entries(pkg[section] ?? {})) {
      const item = outdated[name];
      if (!item?.latest) continue;
      const current = item.current || String(spec).replace(/^[~^]/, "");
      if (majorOf(current) === majorOf(item.latest)) {
        const next = updatePackageSpec(String(spec), item.latest);
        if (next !== spec) { pkg[section][name] = next; changed.push(`${name}: ${spec} → ${next}`); }
      } else {
        held.push(`${name}: ${current} → ${item.latest}`);
      }
    }
  }
  if (changed.length) {
    writeFileSync(pkgPath, `${JSON.stringify(pkg, null, 2)}\n`);
    info(`Updating ${changed.length} same-major package(s)...`);
    run(NPM, ["install"]);
    changed.forEach((line) => console.log(`  ${line}`));
    ok("Safe package updates applied");
  } else ok("No same-major direct dependency updates available");
  if (held.length) {
    warn("Major-version upgrades were held for release review:");
    held.forEach((line) => console.log(`  ${line}`));
  }
  info("Running dependency security audit...");
  let audit = spawnSync(NPM, ["audit", "--audit-level=moderate"], { cwd: ROOT, stdio: "inherit", shell: false });
  if (audit.status !== 0) {
    warn("Audit found remediable issues; running npm audit fix without --force...");
    run(NPM, ["audit", "fix"]);
    audit = spawnSync(NPM, ["audit", "--audit-level=moderate"], { cwd: ROOT, stdio: "inherit", shell: false });
    if (audit.status !== 0) throw new Error("Dependency audit still reports moderate-or-higher findings. Major/breaking fixes were not forced; review the audit output.");
  }
  ok("Dependency audit passed");
}

async function collectEnvironmentCli({ reconfigure = false } = {}) {
  const rl = readline.createInterface({ input: process.stdin, output: process.stdout });
  const env = loadEnv();
  const ask = async (key, label, fallback = "") => {
    if (!reconfigure && String(env[key] ?? "").trim()) return env[key];
    env[key] = await promptText(rl, label, env[key] || fallback);
    return env[key];
  };
  console.log("\nEnvironment setup\n");
  await ask("DATABASE_URL", "SQLite URL", "file:./dev.db");
  await ask("APP_URL", "Application URL", "http://localhost:3000");
  await ask("NEXT_PUBLIC_FIREBASE_API_KEY", "Firebase Web API key");
  await ask("NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN", "Firebase Auth domain");
  await ask("NEXT_PUBLIC_FIREBASE_PROJECT_ID", "Firebase Web project ID");
  await ask("NEXT_PUBLIC_FIREBASE_APP_ID", "Firebase Web app ID");

  if (reconfigure || !env.FIREBASE_PROJECT_ID || !env.FIREBASE_CLIENT_EMAIL || !env.FIREBASE_PRIVATE_KEY) {
    const servicePath = await promptText(rl, "Firebase service-account JSON path (leave blank for manual fields)", "");
    if (servicePath) {
      const json = JSON.parse(readFileSync(resolve(servicePath.replace(/^~(?=$|[/\\])/, homedir())), "utf8"));
      env.FIREBASE_PROJECT_ID = json.project_id || env.FIREBASE_PROJECT_ID || "";
      env.FIREBASE_CLIENT_EMAIL = json.client_email || env.FIREBASE_CLIENT_EMAIL || "";
      env.FIREBASE_PRIVATE_KEY = json.private_key || env.FIREBASE_PRIVATE_KEY || "";
    } else {
      await ask("FIREBASE_PROJECT_ID", "Firebase Admin project ID", env.NEXT_PUBLIC_FIREBASE_PROJECT_ID || "");
      await ask("FIREBASE_CLIENT_EMAIL", "Firebase Admin client email");
      if (reconfigure || !env.FIREBASE_PRIVATE_KEY) env.FIREBASE_PRIVATE_KEY = await promptSecret("Firebase Admin private key (use \\n for line breaks if pasted on one line)");
    }
  }
  if (!env.SESSION_SECRET || env.SESSION_SECRET.length < 32) {
    env.SESSION_SECRET = randomSecret(48);
    ok("Generated SESSION_SECRET");
  }
  if (!env.INITIAL_ADMIN_SETUP_TOKEN || env.INITIAL_ADMIN_SETUP_TOKEN.length < 32) {
    env.INITIAL_ADMIN_SETUP_TOKEN = randomSecret(32);
    ok("Generated one-time INITIAL_ADMIN_SETUP_TOKEN");
  }
  env.INITIAL_ADMIN_EMAIL = await promptText(rl, "Initial administrator email (optional restriction)", env.INITIAL_ADMIN_EMAIL || "");
  rl.close();
  writeEnv(env);
  ok(".env written with owner-only permissions where supported");
  return env;
}

