function parseVersion(input = "") {
  const match = String(input).match(/(\d+)\.(\d+)\.(\d+)/);
  return match ? match.slice(1).map(Number) : [0, 0, 0];
}
function versionAtLeast(actual, required) {
  for (let i = 0; i < 3; i += 1) {
    if (actual[i] > required[i]) return true;
    if (actual[i] < required[i]) return false;
  }
  return true;
}
function majorOf(value = "") { return parseVersion(value)[0]; }
function commandExists(command) {
  const probe = spawnSync(IS_WINDOWS ? "where.exe" : "sh", IS_WINDOWS ? [command] : ["-lc", `command -v ${command}`], { stdio: "ignore" });
  return probe.status === 0;
}
function run(command, args = [], options = {}) {
  const result = spawnSync(command, args, {
    cwd: ROOT,
    env: options.env ?? process.env,
    encoding: "utf8",
    stdio: options.capture ? "pipe" : "inherit",
    shell: false,
  });
  const allowed = options.allowed ?? [0];
  if (!allowed.includes(result.status ?? 1)) {
    const detail = [result.stdout, result.stderr].filter(Boolean).join("\n").trim();
    throw new Error(`${command} ${args.join(" ")} failed${detail ? `:\n${detail}` : ""}`);
  }
  return result;
}
function parseEnv(text) {
  const out = {};
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith("#") || !line.includes("=")) continue;
    const idx = line.indexOf("=");
    const key = line.slice(0, idx).trim();
    let value = line.slice(idx + 1).trim();
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
      try { value = JSON.parse(value); } catch { value = value.slice(1, -1); }
    }
    out[key] = value.replace(/\\n/g, "\n");
  }
  return out;
}
function loadEnv() {
  const base = existsSync(ENV_EXAMPLE_PATH) ? parseEnv(readFileSync(ENV_EXAMPLE_PATH, "utf8")) : {};
  const local = existsSync(ENV_PATH) ? parseEnv(readFileSync(ENV_PATH, "utf8")) : {};
  return { ...base, ...local };
}
function writeEnv(values) {
  const preferred = existsSync(ENV_EXAMPLE_PATH) ? Object.keys(parseEnv(readFileSync(ENV_EXAMPLE_PATH, "utf8"))) : [];
  const keys = [...preferred, ...Object.keys(values).filter((key) => !preferred.includes(key))];
  const lines = ["# CyberLab Studio Pro - generated by the unified setup tool"];
  for (const key of keys) {
    const value = values[key] ?? "";
    lines.push(`${key}=${JSON.stringify(String(value).replace(/\r?\n/g, "\\n"))}`);
  }
  writeFileSync(ENV_PATH, `${lines.join("\n")}\n`, { mode: 0o600 });
  for (const [key, value] of Object.entries(values)) process.env[key] = String(value ?? "");
}
function effectiveEnv() { return { ...loadEnv(), ...process.env }; }
function randomSecret(bytes = 48) { return randomBytes(bytes).toString("base64url"); }

async function promptText(rl, label, fallback = "") {
  const answer = (await rl.question(`${label}${fallback ? ` [${fallback}]` : ""}: `)).trim();
  return answer || fallback;
}
async function promptYesNo(rl, label, fallback = true) {
  const marker = fallback ? "Y/n" : "y/N";
  const answer = (await rl.question(`${label} (${marker}): `)).trim().toLowerCase();
  if (!answer) return fallback;
  return answer === "y" || answer === "yes";
}
async function promptSecret(label) {
  if (!process.stdin.isTTY || !process.stdin.setRawMode) {
    const rl = readline.createInterface({ input: process.stdin, output: process.stdout });
    const value = await rl.question(`${label}: `);
    rl.close();
    return value;
  }
  return await new Promise((resolveSecret, reject) => {
    process.stdout.write(`${label}: `);
    let value = "";
    const previous = process.stdin.isRaw;
    process.stdin.setRawMode(true);
    process.stdin.resume();
    const onData = (chunk) => {
      const char = chunk.toString("utf8");
      if (char === "\u0003") {
        cleanup();
        reject(new Error("Cancelled."));
      } else if (char === "\r" || char === "\n") {
        cleanup();
        process.stdout.write("\n");
        resolveSecret(value);
      } else if (char === "\u007f" || char === "\b") {
        if (value) { value = value.slice(0, -1); process.stdout.write("\b \b"); }
      } else if (/^[\x20-\x7E]+$/.test(char)) {
        value += char;
        process.stdout.write("•".repeat(char.length));
      }
    };
    const cleanup = () => {
      process.stdin.off("data", onData);
      process.stdin.setRawMode(Boolean(previous));
      process.stdin.pause();
    };
    process.stdin.on("data", onData);
  });
}

function checkNode() {
  const actual = parseVersion(process.versions.node);
  if (!versionAtLeast(actual, MIN_NODE)) throw new Error(`Node.js 24.12.0+ is required. Current: ${process.versions.node}. Run cyberlab.ps1/cyberlab.sh so the local runtime can be bootstrapped.`);
}

