function provisionAdminWithInput(input) {
  const payload = JSON.stringify(input);
  const child = spawnSync(NPX, ["tsx", "scripts/provision-first-admin.ts"], {
    cwd: ROOT,
    env: { ...process.env, ...loadEnv() },
    input: payload,
    encoding: "utf8",
    stdio: ["pipe", "pipe", "pipe"],
    shell: false,
  });
  if (child.status !== 0) throw new Error((child.stderr || child.stdout || "Administrator provisioning failed.").trim());
  return JSON.parse(child.stdout.trim() || "{}");
}
async function maybeProvisionAdmin() {
  const rl = readline.createInterface({ input: process.stdin, output: process.stdout });
  const should = await promptYesNo(rl, "Create the first Administrator account now?", true);
  if (!should) { rl.close(); return; }
  const env = loadEnv();
  const email = await promptText(rl, "Administrator email", env.INITIAL_ADMIN_EMAIL || "");
  const displayName = await promptText(rl, "Administrator display name", "CyberLab Admin");
  rl.close();
  const password = await promptSecret("Administrator password (12-128 characters)");
  env.INITIAL_ADMIN_EMAIL = email;
  if (!env.INITIAL_ADMIN_SETUP_TOKEN || env.INITIAL_ADMIN_SETUP_TOKEN.length < 32) env.INITIAL_ADMIN_SETUP_TOKEN = randomSecret(32);
  writeEnv(env);
  const result = provisionAdminWithInput({ setupToken: env.INITIAL_ADMIN_SETUP_TOKEN, email, displayName, password });
  if (result.alreadyConfigured) {
    warn("An Administrator already exists; first-run provisioning was skipped.");
    return;
  }
  env.INITIAL_ADMIN_SETUP_TOKEN = "";
  writeEnv(env);
  ok(`Administrator created: ${result.email}`);
  ok("One-time setup token removed from .env");
}

function findCloudflared() {
  if (commandExists("cloudflared")) return "cloudflared";
  if (existsSync(CLOUDFLARED_LOCAL)) return CLOUDFLARED_LOCAL;
  return null;
}
async function installCloudflared() {
  const existing = findCloudflared();
  if (existing) return existing;
  mkdirSync(LOCAL_BIN, { recursive: true });
  const cpu = arch() === "arm64" ? "arm64" : "amd64";
  const asset = IS_WINDOWS ? `cloudflared-windows-${cpu}.exe` : `cloudflared-linux-${cpu}`;
  const url = `https://github.com/cloudflare/cloudflared/releases/latest/download/${asset}`;
  info(`Downloading official cloudflared (${asset})...`);
  const response = await fetch(url, { redirect: "follow" });
  if (!response.ok) throw new Error(`cloudflared download failed: HTTP ${response.status}`);
  const buffer = Buffer.from(await response.arrayBuffer());
  writeFileSync(CLOUDFLARED_LOCAL, buffer);
  if (!IS_WINDOWS) chmodSync(CLOUDFLARED_LOCAL, 0o755);
  ok(`cloudflared installed locally (${createHash("sha256").update(buffer).digest("hex").slice(0, 12)}… SHA-256)`);
  return CLOUDFLARED_LOCAL;
}

async function configureTunnel() {
  const rl = readline.createInterface({ input: process.stdin, output: process.stdout });
  console.log("\nCloudflare Tunnel setup\n1) Quick temporary public URL\n2) Named tunnel + custom hostname\n3) Skip\n");
  const choice = await promptText(rl, "Select", "3");
  if (choice === "3") { rl.close(); return; }
  const cloudflared = await installCloudflared();
  if (choice === "1") {
    rl.close();
    warn("Quick Tunnel generates a temporary trycloudflare.com URL. Keep this terminal open while sharing it.");
    run(cloudflared, ["tunnel", "--url", "http://localhost:3000"]);
    return;
  }
  const name = await promptText(rl, "Tunnel name", "cyberlab");
  const hostname = await promptText(rl, "Public hostname (for example cyberlab.example.com)");
  if (!hostname.includes(".")) throw new Error("Enter a valid public hostname.");
  rl.close();
  info("Opening Cloudflare browser login...");
  run(cloudflared, ["tunnel", "login"]);
  const listBefore = run(cloudflared, ["tunnel", "list", "--output", "json"], { capture: true, allowed: [0] });
  let tunnels = JSON.parse(listBefore.stdout || "[]");
  let tunnel = tunnels.find((item) => item.name === name);
  if (!tunnel) {
    run(cloudflared, ["tunnel", "create", name]);
    tunnels = JSON.parse(run(cloudflared, ["tunnel", "list", "--output", "json"], { capture: true }).stdout || "[]");
    tunnel = tunnels.find((item) => item.name === name);
  }
  if (!tunnel?.id) throw new Error("Could not resolve the created Cloudflare Tunnel ID.");
  run(cloudflared, ["tunnel", "route", "dns", name, hostname]);
  const credentials = join(homedir(), ".cloudflared", `${tunnel.id}.json`).replace(/\\/g, "/");
  const configDir = join(ROOT, "deploy", "cloudflared");
  mkdirSync(configDir, { recursive: true });
  const configPath = join(configDir, "config.yml");
  writeFileSync(configPath, `tunnel: ${tunnel.id}\ncredentials-file: ${credentials}\ningress:\n  - hostname: ${hostname}\n    service: http://localhost:3000\n  - service: http_status:404\n`);
  const env = loadEnv();
  env.APP_URL = `https://${hostname}`;
  writeEnv(env);
  ok(`Named tunnel configured for https://${hostname}`);
  warn(`Add ${hostname} to Firebase Authentication → Authorized domains before public sign-in.`);
  info(`Run: ${cloudflared} tunnel --config "${configPath}" run ${name}`);
}

function sourceUpdate() {
  if (!commandExists("git") || !existsSync(join(ROOT, ".git"))) {
    warn("Git checkout not detected; source update skipped. Download a fresh release ZIP for source updates.");
    return;
  }
  const dirty = run("git", ["status", "--porcelain"], { capture: true }).stdout.trim();
  if (dirty) {
    warn("Repository has local changes; git pull skipped to avoid overwriting them.");
    return;
  }
  info("Updating repository with fast-forward only...");
  run("git", ["pull", "--ff-only"]);
  ok("Repository updated");
}

async function setupFlow({ web = false, skipUpdate = false } = {}) {
  checkNode();
  if (web) return startWebWizard();
  console.log(color("36", `\nCyberLab Studio Pro v${VERSION} unified setup\n`));
  installLockedDependencies();
  if (!skipUpdate) {
    const rl = readline.createInterface({ input: process.stdin, output: process.stdout });
    const shouldUpdate = await promptYesNo(rl, "Auto-update outdated same-major packages?", true);
    rl.close();
    if (shouldUpdate) safeDependencyUpdate();
  }
  await collectEnvironmentCli();
  setupDatabase();
  await maybeProvisionAdmin();
  const rl = readline.createInterface({ input: process.stdin, output: process.stdout });
  const tunnel = await promptYesNo(rl, "Configure Cloudflare Tunnel now?", false);
  const startNow = await promptYesNo(rl, "Start CyberLab now?", true);
  rl.close();
  if (tunnel) await configureTunnel();
  ok("CyberLab setup complete");
  if (startNow) startApp("dev");
}

function startApp(mode = "production") {
  const env = loadEnv();
  for (const [key, value] of Object.entries(env)) process.env[key] = String(value ?? "");
  if (mode === "dev") return run(NPM, ["run", "dev"]);
  run(NPM, ["run", "build"]);
  return run(NPM, ["run", "start"]);
}

async function updateFlow() {
  console.log(color("36", "\nCyberLab update\n"));
  sourceUpdate();
  installLockedDependencies();
  safeDependencyUpdate();
  setupDatabase();
  ok("Update complete");
}

