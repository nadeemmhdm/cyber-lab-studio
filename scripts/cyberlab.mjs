async function startWebWizard() {
  checkNode();
  if (!existsSync(join(ROOT, "node_modules"))) installLockedDependencies();
  const token = randomSecret(24);
  const env = loadEnv();
  const server = createServer(async (req, res) => {
    res.setHeader("Cache-Control", "no-store");
    if (req.method === "GET" && req.url === "/") {
      res.writeHead(200, { "content-type": "text/html; charset=utf-8" });
      res.end(wizardHtml(token, env));
      return;
    }
    if (req.method === "POST" && req.url === "/setup") {
      try {
        let body = "";
        for await (const chunk of req) { body += chunk; if (body.length > 1_000_000) throw new Error("Request too large."); }
        const input = JSON.parse(body);
        if (input.token !== token) throw new Error("Invalid local setup token.");
        const next = loadEnv();
        for (const key of ["APP_URL", "DATABASE_URL", "NEXT_PUBLIC_FIREBASE_API_KEY", "NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN", "NEXT_PUBLIC_FIREBASE_PROJECT_ID", "NEXT_PUBLIC_FIREBASE_APP_ID"]) next[key] = String(input[key] || "").trim();
        if (input.serviceAccount) {
          const service = JSON.parse(input.serviceAccount);
          next.FIREBASE_PROJECT_ID = service.project_id || "";
          next.FIREBASE_CLIENT_EMAIL = service.client_email || "";
          next.FIREBASE_PRIVATE_KEY = service.private_key || "";
        }
        if (!next.SESSION_SECRET || next.SESSION_SECRET.length < 32) next.SESSION_SECRET = randomSecret(48);
        if (!next.INITIAL_ADMIN_SETUP_TOKEN || next.INITIAL_ADMIN_SETUP_TOKEN.length < 32) next.INITIAL_ADMIN_SETUP_TOKEN = randomSecret(32);
        next.INITIAL_ADMIN_EMAIL = String(input.adminEmail || "").trim().toLowerCase();
        writeEnv(next);
        if (input.packageUpdate === "yes") safeDependencyUpdate();
        setupDatabase();
        if (input.adminEmail && input.adminPassword) {
          const admin = provisionAdminWithInput({ setupToken: next.INITIAL_ADMIN_SETUP_TOKEN, email: input.adminEmail, displayName: input.adminName || "CyberLab Admin", password: input.adminPassword });
          if (!admin.alreadyConfigured) { next.INITIAL_ADMIN_SETUP_TOKEN = ""; writeEnv(next); }
        }
        res.writeHead(200, { "content-type": "application/json" });
        res.end(JSON.stringify({ ok: true, message: "Setup complete. Run the unified CLI tunnel command for Cloudflare, then start CyberLab." }));
      } catch (error) {
        res.writeHead(400, { "content-type": "application/json" });
        res.end(JSON.stringify({ ok: false, error: error instanceof Error ? error.message : String(error) }));
      }
      return;
    }
    res.writeHead(404); res.end();
  });
  await new Promise((resolveServer) => server.listen(3210, "127.0.0.1", resolveServer));
  const url = "http://127.0.0.1:3210";
  ok(`Local setup web UI: ${url}`);
  try {
    if (IS_WINDOWS) spawn("cmd", ["/c", "start", "", url], { detached: true, stdio: "ignore" }).unref();
    else if (platform() === "darwin") spawn("open", [url], { detached: true, stdio: "ignore" }).unref();
    else spawn("xdg-open", [url], { detached: true, stdio: "ignore" }).unref();
  } catch { /* browser launch is optional */ }
  info("Press Ctrl+C when setup is complete.");
}

async function menu() {
  const rl = readline.createInterface({ input: process.stdin, output: process.stdout });
  console.log(color("36", `\nCyberLab Studio Pro v${VERSION}\n`));
  console.log("1) Setup / repair\n2) Web setup wizard\n3) Update CyberLab + packages\n4) Start development server\n5) Start production server\n6) Configure Cloudflare Tunnel\n7) Doctor\n8) Exit\n");
  const choice = await promptText(rl, "Select", "1");
  rl.close();
  if (choice === "1") return setupFlow({});
  if (choice === "2") return startWebWizard();
  if (choice === "3") return updateFlow();
  if (choice === "4") return startApp("dev");
  if (choice === "5") return startApp("production");
  if (choice === "6") return configureTunnel();
  if (choice === "7") return doctor();
}

function help() {
  console.log(`CyberLab Studio Pro unified CLI\n\nUsage:\n  cyberlab [command]\n\nCommands:\n  setup            Install/repair packages, collect .env, prepare DB, create first admin\n  web              Open local setup web UI on 127.0.0.1:3210\n  update           Fast-forward source (when clean), update packages safely, audit, prepare DB\n  doctor [--ci]    Check runtime/repository/environment prerequisites\n  tunnel           Install/configure Cloudflare Tunnel (quick or named)\n  start [--dev]    Start CyberLab (production by default)\n  help             Show this help\n\nRunning without a command opens the interactive menu.`);
}

async function main() {
  const [command, ...args] = process.argv.slice(2);
  if (!command) return menu();
  if (["help", "--help", "-h"].includes(command)) return help();
  if (command === "doctor") return doctor({ ci: args.includes("--ci") });
  if (command === "setup") return setupFlow({ web: args.includes("--web"), skipUpdate: args.includes("--skip-update") });
  if (command === "web") return startWebWizard();
  if (command === "update") return updateFlow();
  if (command === "tunnel") return configureTunnel();
  if (command === "start") return startApp(args.includes("--dev") ? "dev" : "production");
  throw new Error(`Unknown command: ${command}. Run help for available commands.`);
}

main().catch((error) => {
  fail(error instanceof Error ? error.message : String(error));
  process.exitCode = 1;
});
