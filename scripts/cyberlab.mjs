  console.log(`\nCyberLab Studio Pro v${VERSION} doctor\n`);
  checkNode();
  ok(`Node ${process.versions.node} (${platform()} ${arch()})`);
  if (!commandExists(NPM.replace(".cmd", ""))) throw new Error("npm is not available next to the selected Node runtime.");
  ok("npm available");
  if (commandExists("git")) ok("Git available"); else warn("Git not found; source-code auto-update will be unavailable.");
