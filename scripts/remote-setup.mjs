#!/usr/bin/env node
import { createHash, createSign, randomBytes } from "node:crypto";
import { spawn, spawnSync } from "node:child_process";
import { chmodSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { arch, homedir, platform } from "node:os";
import { join, resolve } from "node:path";
import readline from "node:readline/promises";

const ROOT = resolve(import.meta.dirname, "..");
process.chdir(ROOT);
const IS_WINDOWS = platform() === "win32";
const NPM = IS_WINDOWS ? "npm.cmd" : "npm";
const NPX = IS_WINDOWS ? "npx.cmd" : "npx";
const ENV_PATH = join(ROOT, ".env");
const ENV_EXAMPLE_PATH = join(ROOT, ".env.example");
const LOCAL_BIN = join(ROOT, ".cyberlab", "bin");
const CLOUDFLARED = join(LOCAL_BIN, IS_WINDOWS ? "cloudflared.exe" : "cloudflared");
const maintenance = process.argv.includes("--maintenance");

const ok = (text) => console.log(`✓ ${text}`);
const info = (text) => console.log(`• ${text}`);
const warn = (text) => console.log(`! ${text}`);

function run(command, args = [], options = {}) {
  const result = spawnSync(command, args, {
    cwd: ROOT,
    env: options.env ?? process.env,
    encoding: "utf8",
    stdio: options.capture ? "pipe" : "inherit",
    shell: false,
  });
  const allowed = options.allowed ?? [0];
  if (!allowed.includes(result.status ?? 1)) {
    const detail = [result.stdout, result.stderr].filter(Boolean).join("\n").trim();
    throw new Error(`${command} ${args.join(" ")} failed${detail ? `:\n${detail}` : ""}`);
  }
  return result;
}
function commandExists(command) {
  return spawnSync(IS_WINDOWS ? "where.exe" : "sh", IS_WINDOWS ? [command] : ["-lc", `command -v ${command}`], { stdio: "ignore" }).status === 0;
}
function parseEnv(text) {
  const out = {};
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith("#") || !line.includes("=")) continue;
    const i = line.indexOf("=");
    const key = line.slice(0, i).trim();
    let value = line.slice(i + 1).trim();
    if (value.startsWith('"') && value.endsWith('"')) {
      try { value = JSON.parse(value); } catch { value = value.slice(1, -1); }
    }
    out[key] = value.replace(/\\n/g, "\n");
  }
  return out;
}
function loadEnv() {
  return {
    ...(existsSync(ENV_EXAMPLE_PATH) ? parseEnv(readFileSync(ENV_EXAMPLE_PATH, "utf8")) : {}),
    ...(existsSync(ENV_PATH) ? parseEnv(readFileSync(ENV_PATH, "utf8")) : {}),
  };
}
function writeEnv(values) {
  const exampleKeys = existsSync(ENV_EXAMPLE_PATH) ? Object.keys(parseEnv(readFileSync(ENV_EXAMPLE_PATH, "utf8"))) : [];
  const keys = [...exampleKeys, ...Object.keys(values).filter((key) => !exampleKeys.includes(key))];
  const lines = ["# CyberLab Studio Pro - generated by the one-line installer"];
  for (const key of keys) lines.push(`${key}=${JSON.stringify(String(values[key] ?? "").replace(/\r?\n/g, "\\n"))}`);
  writeFileSync(ENV_PATH, `${lines.join("\n")}\n`, { mode: 0o600 });
  for (const [key, value] of Object.entries(values)) process.env[key] = String(value ?? "");
}
function randomSecret(bytes = 48) { return randomBytes(bytes).toString("base64url"); }
async function ask(rl, label, fallback = "") {
  const value = (await rl.question(`${label}${fallback ? ` [${fallback}]` : ""}: `)).trim();
  return value || fallback;
}
async function yesNo(rl, label, fallback = true) {
  const value = (await rl.question(`${label} (${fallback ? "Y/n" : "y/N"}): `)).trim().toLowerCase();
  return value ? ["y", "yes"].includes(value) : fallback;
}
async function secret(label) {
  if (!process.stdin.isTTY || !process.stdin.setRawMode) {
    const rl = readline.createInterface({ input: process.stdin, output: process.stdout });
    const value = await rl.question(`${label}: `);
    rl.close();
    return value;
  }
  return new Promise((resolveSecret, reject) => {
    process.stdout.write(`${label}: `);
    let value = "";
    const wasRaw = process.stdin.isRaw;
    process.stdin.setRawMode(true);
    process.stdin.resume();
    const cleanup = () => {
      process.stdin.off("data", onData);
      process.stdin.setRawMode(Boolean(wasRaw));
      process.stdin.pause();
    };
    const onData = (chunk) => {
      const char = chunk.toString("utf8");
      if (char === "\u0003") { cleanup(); reject(new Error("Cancelled.")); return; }
      if (char === "\r" || char === "\n") { cleanup(); process.stdout.write("\n"); resolveSecret(value); return; }
      if (char === "\u007f" || char === "\b") {
        if (value) { value = value.slice(0, -1); process.stdout.write("\b \b"); }
        return;
      }
      if (/^[\x20-\x7E]+$/.test(char)) { value += char; process.stdout.write("•".repeat(char.length)); }
    };
    process.stdin.on("data", onData);
  });
}

function installAndUpdatePackages() {
  info("Installing the repository's approved dependency graph...");
  run(NPM, ["ci"]);
  ok("Missing/locked packages installed");

  const outdated = run(NPM, ["outdated", "--json"], { capture: true, allowed: [0, 1] });
  let parsed = {};
  try { parsed = JSON.parse(outdated.stdout || "{}"); } catch { parsed = {}; }
  const names = Object.keys(parsed);
  if (names.length) {
    info(`Found ${names.length} package(s) with newer versions. Applying non-persistent updates allowed by package.json ranges...`);
    run(NPM, ["update", "--no-save", "--package-lock=false"], { allowed: [0] });
    const major = names.filter((name) => {
      const item = parsed[name];
      const current = String(item?.current ?? "0").split(".")[0];
      const latest = String(item?.latest ?? "0").split(".")[0];
      return current && latest && current !== latest;
    });
    if (major.length) warn(`Major-version upgrades are intentionally held for tested repository releases: ${major.join(", ")}`);
  } else ok("Packages are current for the installed graph");

  info("Running dependency security audit...");
  const audit = spawnSync(NPM, ["audit", "--audit-level=moderate"], { cwd: ROOT, stdio: "inherit", shell: false });
  if (audit.status !== 0) throw new Error("npm audit reports moderate-or-higher findings. The installer will not force breaking dependency upgrades.");
  ok("Dependency audit passed");
}

async function collectEnvironment() {
  const env = loadEnv();
  const rl = readline.createInterface({ input: process.stdin, output: process.stdout });
  console.log("\nFirebase + application configuration\n");
  env.DATABASE_URL = await ask(rl, "SQLite database URL", env.DATABASE_URL || "file:./dev.db");
  env.APP_URL = "http://localhost:3000";
  env.NEXT_PUBLIC_FIREBASE_API_KEY = await ask(rl, "Firebase Web API key", env.NEXT_PUBLIC_FIREBASE_API_KEY || "");
  env.NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN = await ask(rl, "Firebase Auth domain", env.NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN || "");
  env.NEXT_PUBLIC_FIREBASE_PROJECT_ID = await ask(rl, "Firebase project ID", env.NEXT_PUBLIC_FIREBASE_PROJECT_ID || "");
  env.NEXT_PUBLIC_FIREBASE_APP_ID = await ask(rl, "Firebase Web app ID", env.NEXT_PUBLIC_FIREBASE_APP_ID || "");

  console.log("\nFirebase Admin credentials\nTip: download a service-account JSON from Firebase/Google Cloud and enter its path.\n");
  const servicePath = await ask(rl, "Service-account JSON path (blank = enter fields manually)", "");
  if (servicePath) {
    const expanded = servicePath.replace(/^~(?=$|[/\\])/, homedir());
    const json = JSON.parse(readFileSync(resolve(expanded), "utf8"));
    env.FIREBASE_PROJECT_ID = json.project_id || env.NEXT_PUBLIC_FIREBASE_PROJECT_ID || "";
    env.FIREBASE_CLIENT_EMAIL = json.client_email || "";
    env.FIREBASE_PRIVATE_KEY = json.private_key || "";
  } else {
    env.FIREBASE_PROJECT_ID = await ask(rl, "Firebase Admin project ID", env.FIREBASE_PROJECT_ID || env.NEXT_PUBLIC_FIREBASE_PROJECT_ID || "");
    env.FIREBASE_CLIENT_EMAIL = await ask(rl, "Firebase Admin client email", env.FIREBASE_CLIENT_EMAIL || "");
    rl.close();
    env.FIREBASE_PRIVATE_KEY = await secret("Firebase Admin private key (paste with \\n if one line)");
    if (!env.SESSION_SECRET || env.SESSION_SECRET.length < 32) env.SESSION_SECRET = randomSecret(48);
    if (!env.INITIAL_ADMIN_SETUP_TOKEN || env.INITIAL_ADMIN_SETUP_TOKEN.length < 32) env.INITIAL_ADMIN_SETUP_TOKEN = randomSecret(32);
    writeEnv(env);
    return env;
  }
  rl.close();
  if (!env.SESSION_SECRET || env.SESSION_SECRET.length < 32) env.SESSION_SECRET = randomSecret(48);
  if (!env.INITIAL_ADMIN_SETUP_TOKEN || env.INITIAL_ADMIN_SETUP_TOKEN.length < 32) env.INITIAL_ADMIN_SETUP_TOKEN = randomSecret(32);
  writeEnv(env);
  return env;
}

function setupDatabase() {
  info("Generating Prisma client...");
  run(NPM, ["run", "db:generate"]);
  info("Creating/updating SQLite schema...");
  run(NPX, ["prisma", "db", "push", "--skip-generate"]);
  info("Seeding roles and all 30 labs...");
  run(NPM, ["run", "db:seed"]);
  ok("Database ready");
}

async function provisionFirstAdmin(env) {
  const rl = readline.createInterface({ input: process.stdin, output: process.stdout });
  console.log("\nInitial Administrator account\n");
  const email = await ask(rl, "Administrator email", env.INITIAL_ADMIN_EMAIL || "");
  const displayName = await ask(rl, "Administrator display name", "CyberLab Admin");
  rl.close();
  const password = await secret("Administrator password (12-128 characters)");
  env.INITIAL_ADMIN_EMAIL = email.trim().toLowerCase();
  writeEnv(env);
  const payload = JSON.stringify({ setupToken: env.INITIAL_ADMIN_SETUP_TOKEN, email, displayName, password });
  const result = spawnSync(NPX, ["tsx", "scripts/provision-first-admin.ts"], {
    cwd: ROOT,
    env: { ...process.env, ...env },
    input: payload,
    encoding: "utf8",
    stdio: ["pipe", "pipe", "pipe"],
    shell: false,
  });
  if (result.status !== 0) throw new Error((result.stderr || result.stdout || "Administrator provisioning failed.").trim());
  const data = JSON.parse(result.stdout.trim() || "{}");
  if (data.alreadyConfigured) {
    warn("An Administrator already exists; first-run account creation skipped.");
    return;
  }
  env.INITIAL_ADMIN_SETUP_TOKEN = "";
  writeEnv(env);
  ok(`Administrator created: ${data.email}`);
}

async function installCloudflared() {
  if (commandExists("cloudflared")) return "cloudflared";
  if (existsSync(CLOUDFLARED)) return CLOUDFLARED;
  mkdirSync(LOCAL_BIN, { recursive: true });
  const cpu = arch() === "arm64" ? "arm64" : "amd64";
  const asset = IS_WINDOWS ? `cloudflared-windows-${cpu}.exe` : `cloudflared-linux-${cpu}`;
  const url = `https://github.com/cloudflare/cloudflared/releases/latest/download/${asset}`;
  info(`Downloading official cloudflared (${asset})...`);
  const response = await fetch(url, { redirect: "follow" });
  if (!response.ok) throw new Error(`cloudflared download failed: HTTP ${response.status}`);
  const bytes = Buffer.from(await response.arrayBuffer());
  writeFileSync(CLOUDFLARED, bytes);
  if (!IS_WINDOWS) chmodSync(CLOUDFLARED, 0o755);
  ok(`cloudflared ready (${createHash("sha256").update(bytes).digest("hex").slice(0, 12)}… SHA-256)`);
  return CLOUDFLARED;
}

function base64url(value) { return Buffer.from(value).toString("base64url"); }
async function serviceAccountAccessToken(env) {
  const now = Math.floor(Date.now() / 1000);
  const header = base64url(JSON.stringify({ alg: "RS256", typ: "JWT" }));
  const claim = base64url(JSON.stringify({
    iss: env.FIREBASE_CLIENT_EMAIL,
    scope: "https://www.googleapis.com/auth/cloud-platform",
    aud: "https://oauth2.googleapis.com/token",
    iat: now,
    exp: now + 3600,
  }));
  const unsigned = `${header}.${claim}`;
  const signer = createSign("RSA-SHA256");
  signer.update(unsigned);
  signer.end();
  const assertion = `${unsigned}.${signer.sign(env.FIREBASE_PRIVATE_KEY).toString("base64url")}`;
  const body = new URLSearchParams({ grant_type: "urn:ietf:params:oauth:grant-type:jwt-bearer", assertion });
  const response = await fetch("https://oauth2.googleapis.com/token", { method: "POST", headers: { "content-type": "application/x-www-form-urlencoded" }, body });
  if (!response.ok) throw new Error(`Google OAuth token request failed (${response.status})`);
  const json = await response.json();
  return json.access_token;
}
async function authorizeFirebaseDomain(env, hostname) {
  if (!hostname) return;
  try {
    const token = await serviceAccountAccessToken(env);
    const base = `https://identitytoolkit.googleapis.com/admin/v2/projects/${encodeURIComponent(env.FIREBASE_PROJECT_ID)}/config`;
    const headers = { Authorization: `Bearer ${token}`, "content-type": "application/json", "x-goog-user-project": env.FIREBASE_PROJECT_ID };
    const currentResponse = await fetch(base, { headers });
    if (!currentResponse.ok) throw new Error(`read config HTTP ${currentResponse.status}`);
    const current = await currentResponse.json();
    const domains = Array.from(new Set([...(current.authorizedDomains || []), hostname]));
    const patch = await fetch(`${base}?updateMask=authorizedDomains`, { method: "PATCH", headers, body: JSON.stringify({ authorizedDomains: domains }) });
    if (!patch.ok) throw new Error(`update config HTTP ${patch.status}`);
    ok(`Firebase Authorized domains updated: ${hostname}`);
  } catch (error) {
    warn(`Could not auto-add ${hostname} to Firebase Authorized domains (${error instanceof Error ? error.message : error}).`);
    warn(`Add it manually in Firebase Authentication → Settings → Authorized domains before public sign-in.`);
  }
}

async function waitForQuickTunnelUrl(child, timeoutMs = 45_000) {
  return new Promise((resolveUrl, reject) => {
    let buffer = "";
    const timer = setTimeout(() => reject(new Error("Timed out waiting for the Quick Tunnel public URL.")), timeoutMs);
    const consume = (chunk) => {
      const text = chunk.toString();
      process.stdout.write(text);
      buffer += text;
      const match = buffer.match(/https:\/\/[a-z0-9-]+\.trycloudflare\.com/i);
      if (match) { clearTimeout(timer); resolveUrl(match[0]); }
    };
    child.stdout?.on("data", consume);
    child.stderr?.on("data", consume);
    child.once("exit", (code) => { clearTimeout(timer); reject(new Error(`cloudflared exited before a public URL was ready (code ${code}).`)); });
  });
}

async function configureNamedTunnel(cloudflared, env, hostname, name) {
  info("Cloudflare authorization will open in your browser once; approve the domain/account for this machine.");
  run(cloudflared, ["tunnel", "login"]);
  let tunnels = JSON.parse(run(cloudflared, ["tunnel", "list", "--output", "json"], { capture: true }).stdout || "[]");
  let tunnel = tunnels.find((item) => item.name === name);
  if (!tunnel) {
    run(cloudflared, ["tunnel", "create", name]);
    tunnels = JSON.parse(run(cloudflared, ["tunnel", "list", "--output", "json"], { capture: true }).stdout || "[]");
    tunnel = tunnels.find((item) => item.name === name);
  }
  if (!tunnel?.id) throw new Error("Could not resolve the Cloudflare Tunnel ID.");
  run(cloudflared, ["tunnel", "route", "dns", name, hostname]);
  const credentials = join(homedir(), ".cloudflared", `${tunnel.id}.json`).replace(/\\/g, "/");
  const configDir = join(ROOT, "deploy", "cloudflared");
  mkdirSync(configDir, { recursive: true });
  const configPath = join(configDir, "config.yml");
  writeFileSync(configPath, `tunnel: ${tunnel.id}\ncredentials-file: ${credentials}\ningress:\n  - hostname: ${hostname}\n    service: http://localhost:3000\n  - service: http_status:404\n`);
  env.APP_URL = `https://${hostname}`;
  writeEnv(env);
  await authorizeFirebaseDomain(env, hostname);
  return { mode: "named", cloudflared, name, configPath, publicUrl: env.APP_URL };
}

async function choosePublicAccess(env) {
  const rl = readline.createInterface({ input: process.stdin, output: process.stdout });
  console.log("\nPublic access\n1) Quick worldwide HTTPS URL (no Cloudflare account required)\n2) Permanent Cloudflare hostname/domain\n3) Local only\n");
  const choice = await ask(rl, "Select", "1");
  if (choice === "3") { rl.close(); env.APP_URL = "http://localhost:3000"; writeEnv(env); return { mode: "local" }; }
  const cloudflared = await installCloudflared();
  if (choice === "2") {
    const hostname = await ask(rl, "Public hostname (example: lab.example.com)");
    const name = await ask(rl, "Cloudflare Tunnel name", "cyberlab");
    rl.close();
    if (!hostname.includes(".")) throw new Error("Enter a valid public hostname.");
    return configureNamedTunnel(cloudflared, env, hostname, name);
  }
  rl.close();
  info("Starting Cloudflare Quick Tunnel to obtain a public hostname...");
  const child = spawn(cloudflared, ["tunnel", "--url", "http://localhost:3000"], { cwd: ROOT, stdio: ["ignore", "pipe", "pipe"], shell: false });
  const publicUrl = await waitForQuickTunnelUrl(child);
  const hostname = new URL(publicUrl).hostname;
  env.APP_URL = publicUrl;
  writeEnv(env);
  await authorizeFirebaseDomain(env, hostname);
  ok(`Worldwide URL ready: ${publicUrl}`);
  return { mode: "quick", cloudflared, child, publicUrl };
}

async function waitForApp(url = "http://127.0.0.1:3000", timeoutMs = 90_000) {
  const end = Date.now() + timeoutMs;
  while (Date.now() < end) {
    try {
      const response = await fetch(`${url}/api/health`, { redirect: "manual" });
      if (response.status < 500) return;
    } catch { /* starting */ }
    await new Promise((resolveDelay) => setTimeout(resolveDelay, 1000));
  }
  throw new Error("CyberLab did not become ready on localhost:3000 within 90 seconds.");
}

async function launch(env, tunnel) {
  info("Building CyberLab for production...");
  run(NPM, ["run", "build"], { env: { ...process.env, ...env } });
  info("Starting CyberLab on localhost:3000...");
  const app = spawn(NPM, ["run", "start"], { cwd: ROOT, env: { ...process.env, ...env }, stdio: "inherit", shell: false });
  await waitForApp();
  ok("CyberLab is online locally");

  let tunnelChild = tunnel?.child ?? null;
  if (tunnel?.mode === "named") {
    tunnelChild = spawn(tunnel.cloudflared, ["tunnel", "--config", tunnel.configPath, "run", tunnel.name], { cwd: ROOT, stdio: "inherit", shell: false });
  }
  if (tunnel?.publicUrl) ok(`Public access: ${tunnel.publicUrl}`);
  else ok("Local access: http://localhost:3000");
  console.log("Press Ctrl+C to stop CyberLab" + (tunnelChild ? " and the tunnel." : "."));

  const stop = () => { try { tunnelChild?.kill(); } catch {} try { app.kill(); } catch {} };
  process.once("SIGINT", () => { stop(); process.exit(0); });
  process.once("SIGTERM", () => { stop(); process.exit(0); });
  await new Promise((resolveExit, reject) => {
    app.once("error", reject);
    app.once("exit", (code) => code === 0 || code === null ? resolveExit() : reject(new Error(`CyberLab exited with code ${code}.`)));
  });
}

async function main() {
  console.log("\nCyberLab Studio Pro - automated terminal setup\n");
  installAndUpdatePackages();
  if (maintenance) {
    setupDatabase();
    ok("CyberLab maintenance/update complete");
    return;
  }
  const env = await collectEnvironment();
  setupDatabase();
  await provisionFirstAdmin(env);
  const tunnel = await choosePublicAccess(env);
  await launch(env, tunnel);
}

main().catch((error) => {
  console.error(`✗ ${error instanceof Error ? error.message : String(error)}`);
  process.exitCode = 1;
});
